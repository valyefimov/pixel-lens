/** Collapses four side values into CSS shorthand: `0 0 0 24px` -> `0 0 0 24px`, `8px 8px 8px 8px` -> `8px`. */
export function shorthand(top: string, right: string, bottom: string, left: string): string {
  const n = (v: string) => (v === "0px" ? "0" : v);
  const [t, r, b, l] = [n(top), n(right), n(bottom), n(left)];
  if (t === r && r === b && b === l) return t;
  if (t === b && r === l) return `${t} ${r}`;
  if (r === l) return `${t} ${r} ${b}`;
  return `${t} ${r} ${b} ${l}`;
}

/** Turns `"Inter", system-ui, sans-serif` into `["Inter", "system-ui", "sans-serif"]`. */
export function splitFontFamily(value: string): string[] {
  return value
    .split(",")
    .map((f) => f.trim().replace(/^["']|["']$/g, ""))
    .filter(Boolean);
}

/** One style change recorded by the live editor. */
export interface StyleEdit {
  selector: string;
  property: string;
  before: string;
  after: string;
}

/**
 * Folds a chronological list of edits into the net change per selector/property,
 * dropping edits that were reverted back to their original value.
 */
export function netEdits(edits: readonly StyleEdit[]): StyleEdit[] {
  const map = new Map<string, StyleEdit>();
  for (const e of edits) {
    const key = `${e.selector}\u0000${e.property}`;
    const prev = map.get(key);
    map.set(key, prev ? { ...prev, after: e.after } : { ...e });
  }
  return [...map.values()].filter((e) => e.before !== e.after);
}

/** Renders edits as a unified-diff-like CSS patch that can be pasted into a PR or a chat with an agent. */
export function editsToDiff(edits: readonly StyleEdit[]): string {
  const bySelector = new Map<string, StyleEdit[]>();
  for (const e of netEdits(edits)) {
    const list = bySelector.get(e.selector) ?? [];
    list.push(e);
    bySelector.set(e.selector, list);
  }
  const blocks: string[] = [];
  for (const [selector, list] of bySelector) {
    const lines = [`  ${selector} {`];
    for (const e of list) {
      if (e.before) lines.push(`-   ${e.property}: ${e.before};`);
      lines.push(`+   ${e.property}: ${e.after};`);
    }
    lines.push("  }");
    blocks.push(lines.join("\n"));
  }
  return blocks.join("\n\n");
}

/** Renders edits as plain CSS rules (the "after" state only). */
export function editsToCss(edits: readonly StyleEdit[]): string {
  const bySelector = new Map<string, string[]>();
  for (const e of netEdits(edits)) {
    const list = bySelector.get(e.selector) ?? [];
    list.push(`  ${e.property}: ${e.after};`);
    bySelector.set(e.selector, list);
  }
  return [...bySelector].map(([sel, decls]) => `${sel} {\n${decls.join("\n")}\n}`).join("\n\n");
}

const SAFE_IDENT = /^-?[_a-zA-Z][_a-zA-Z0-9-]*$/;

/** Escapes an identifier for use in a selector; uses `CSS.escape` when present. */
export function cssEscape(ident: string): string {
  const g = globalThis as { CSS?: { escape?: (s: string) => string } };
  if (g.CSS?.escape) return g.CSS.escape(ident);
  return ident.replace(/([^\w-])/g, "\\$1").replace(/^(\d)/, "\\3$1 ");
}

/** Heuristic: class names generated by CSS-in-JS / CSS modules make poor selectors. */
export function isStableClass(name: string): boolean {
  if (!SAFE_IDENT.test(name)) return false;
  if (/^(css|sc|jsx|emotion|svelte)-[a-z0-9]{4,}$/i.test(name)) return false;
  if (/[_-][a-zA-Z0-9]{5,}$/.test(name) && /\d/.test(name.slice(-6))) return false;
  return true;
}
